rating = input("Введите рейтинг товара (от 1 до 10)> ").strip()

match rating:
    case "10" | "9":
        print("Отличный продукт! 🌟 Настоятельно рекомендую!")
    case "8" | "7" | "6" | "5":
        print("Средний продукт 🤔 Можно попробовать")
    case "4" | "3" | "2" | "1":
        print("Плохой продукт ❌ Не рекомендую")
    case _:
        print("Некорректный ввод")
